#!/usr/bin/env bash
# Generate docs/stories/INDEX.md: every story in this repo and on origin/story/* branches,
# with owner, phase, and branch. Run from the repo root. Safe to re-run; it overwrites INDEX.md.
set -uo pipefail
git rev-parse --git-dir >/dev/null 2>&1 || { echo "not a git repo"; exit 1; }
git fetch -q origin 2>/dev/null || true
OUT="docs/stories/INDEX.md"
mkdir -p docs/stories

# Story ids: local dirs plus remote story branches.
IDS=$( { for d in docs/stories/*/; do [ -f "${d}status.md" ] && basename "$d"; done
         git for-each-ref --format='%(refname:short)' 'refs/remotes/origin/story/*' | sed 's#^origin/story/##'
       } | sort -u )

# read_file <id> <name>: the branch copy is the live one; fall back to the working tree.
read_file() {
  git show "origin/story/$1:docs/stories/$1/$2" 2>/dev/null || cat "docs/stories/$1/$2" 2>/dev/null
}
field() { sed -n "s/^$1:[[:space:]]*//p" | head -1 | tr -d '\r'; }

{
  echo "# Stories"
  echo
  echo "Generated by \`scripts/story-index.sh\`. Do not edit by hand."
  echo
  echo "| Story | Title | Owner | Phase | Branch |"
  echo "|-------|-------|-------|-------|--------|"
  for id in $IDS; do
    status=$(read_file "$id" status.md)
    story=$(read_file "$id" story.md)
    title=$(printf '%s\n' "$story" | tr -d '\r' | sed -e '/^[[:space:]]*$/d' -e 's/^#\+[[:space:]]*//' | head -1 | cut -c1-70 | tr '|' '/')
    owner=$(printf '%s\n' "$status" | field owner)
    if [ -z "$owner" ] && [ -d "docs/stories/$id" ]; then
      owner=$(git log --diff-filter=A --format=%an -- "docs/stories/$id" 2>/dev/null | tail -1)
    fi
    phase=$(printf '%s\n' "$status" | field phase)
    if printf '%s\n' "$status" | grep -qiE '^## Blocked'; then phase="blocked"; fi
    if git show-ref -q --verify "refs/remotes/origin/story/$id"; then
      branch="story/$id"
      git merge-base --is-ancestor "refs/remotes/origin/story/$id" "$(git symbolic-ref -q --short refs/remotes/origin/HEAD 2>/dev/null || echo origin/main)" 2>/dev/null && branch="story/$id (merged)"
    else
      branch="local only"
    fi
    echo "| $id | ${title:--} | ${owner:--} | ${phase:-unknown} | $branch |"
  done
} > "$OUT"
echo "wrote $OUT ($(printf '%s\n' "$IDS" | grep -c .) stories)"
